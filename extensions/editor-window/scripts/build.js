/**
 * Bundles the extension into dist/ with esbuild (Vue included).
 *
 *   node scripts/build.js           one build
 *   node scripts/build.js --watch   rebuild on change
 *
 * The panel slots share one bundle (dist/panels/window.js); each slot's
 * entry (dist/panels/<slot>.js) only names its slot.
 */
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dist = path.join(root, 'dist');
const watch = process.argv.includes('--watch');
const SLOTS = ['default', 'window-2', 'window-3', 'window-4'];

const options = {
    absWorkingDir: root,
    entryPoints: {
        'main': 'source/main.ts',
        'scene': 'source/scene.ts',
        'panels/window': 'source/panels/window/index.ts',
    },
    outdir: dist,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node14',
    sourcemap: 'linked',
    external: ['cc', 'cc/env', 'electron'],
    define: { 'process.env.NODE_ENV': '"production"' },
    minifySyntax: true,
    logLevel: 'info',
};

function writeSlots() {
    fs.mkdirSync(path.join(dist, 'panels'), { recursive: true });
    for (const slot of SLOTS) {
        fs.writeFileSync(
            path.join(dist, 'panels', `${slot}.js`),
            `"use strict";\n// Panel slot "${slot}" (generated by scripts/build.js).\nmodule.exports = require('./window.js').definePanel(${JSON.stringify(slot)});\n`,
        );
    }
}

fs.rmSync(dist, { recursive: true, force: true });

if (watch) {
    esbuild.context({ ...options, plugins: [{ name: 'slots', setup: (b) => b.onEnd(writeSlots) }] }).then((ctx) => ctx.watch());
} else {
    esbuild.buildSync(options);
    writeSlots();
}
